// Renders result/breakdown-c381a85.json as the Markdown tables in packages.md. It reads the breakdown and changes it in
// no way. Usage, in Docker: node scripts/render.mjs result/breakdown-c381a85.json > packages.md
import { readFileSync } from "node:fs";

const j = JSON.parse(readFileSync(process.argv[2], "utf8"));
const short = why => why
  .replace(/^named by (.+), a build tool's configuration$/, "named by $1")
  .replace(/^a bundler helper library, resolved from .+$/, "a bundler helper library")
  .replace(/^declared by (.+?), not a test runner.*, and (the final stage of .+ holds devDependencies|the source tree is incomplete.*)$/, "declared by $1, D1 only: $2")
  .replace(/^reached from no declared dependency, and .+$/, "reached from no declared dependency, D1 only")
  .replace(/ \(from [^)]*\)+/g, "")
  .replace(/\|/g, "\\|");
const seedName = path => path.slice(path.lastIndexOf("node_modules/") + "node_modules/".length);
const rule = why => why.startsWith("not dev") ? "P0" : why.startsWith("a runtime") ? "P4" : why.startsWith("a bundler helper") ? "P3"
  : why.startsWith("imported by ") || why.startsWith("named by a node_modules path") ? "P1" : why.startsWith("named by ") || why.startsWith("jsxImportSource") ? "P2"
  : why.startsWith("the build runs it") ? "P6" : why.endsWith(" runs it") ? "P5" : "D1 only";

const out = [];
out.push(`# The count by package: first run 560, rerun ${j.totals.rerun}`, "");
out.push("Generated by `scripts/render.mjs` from `result/breakdown-c381a85.json`. \"Repositories\" is the number of the 100 repositories that count the package (the judge's count is the sum of these). \"Added\" is the number of repositories that count it in the rerun and did not in the first run; no repository stopped counting a package. \"Why\" gives, for each added repository, the rule and the seed that the judge recorded (production.ts's `why`, followed from the vulnerable copy up through \"a dependency of …\" to the copy a rule made production): `rule: seed — reason`, with how many repositories share it.", "");

out.push("## Seeds behind the additions", "");
out.push("The copy a rule made production, from which following declared dependencies reached the counted package, by the number of added (repository, package) pairs it accounts for. A seed equal to the package means the rule hit the package itself.", "");
out.push("| Seed package | Rule | Added pairs | Repositories |", "| --- | --- | --- | --- |");
const seeds = new Map();
for (const r of j.rows) for (const c of r.counted) if (!c.in_first_run) {
  const key = `${seedName(c.recorded.seed)}\0${c.recorded.seed_rule}`;
  const s = seeds.get(key) ?? { pairs: 0, repos: new Set() };
  s.pairs++; s.repos.add(r.repo); seeds.set(key, s);
}
for (const [key, s] of [...seeds].sort((a, b) => b[1].pairs - a[1].pairs || a[0].localeCompare(b[0]))) {
  const [name, r] = key.split("\0");
  out.push(`| ${name} | ${r} | ${s.pairs} | ${s.repos.size} |`);
}
out.push("");

out.push("## Every package the rerun added", "");
out.push("| Package | First run | Rerun | Added | First-run verdict of the added ones | Why (rule: seed — reason, repositories) |", "| --- | --- | --- | --- | --- | --- |");
for (const p of j.packages.filter(p => p.added)) {
  const why = new Map();
  for (const a of p.repositories_added) {
    const k = `${rule(a.seed_why)}: ${seedName(a.seed)} — ${short(a.seed_why)}`;
    why.set(k, (why.get(k) ?? 0) + 1);
  }
  const whyText = [...why].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0])).map(([k, n]) => `${k} (${n})`).join("; ");
  const verdicts = Object.entries(p.first_run_verdict).sort((a, b) => b[1] - a[1]).map(([k, n]) => `${k} ${n}`).join(", ");
  out.push(`| ${p.name} | ${p.first_run} | ${p.rerun} | +${p.added} | ${verdicts} | ${whyText} |`);
}
out.push("");
const same = j.packages.filter(p => !p.added);
out.push(`## Packages with no change (${same.length})`, "");
out.push(same.sort((a, b) => b.rerun - a.rerun || a.name.localeCompare(b.name)).map(p => `${p.name} ${p.rerun}`).join(", "), "");
console.log(out.join("\n"));
