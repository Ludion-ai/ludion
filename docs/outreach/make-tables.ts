#!/usr/bin/env node
// Builds docs/outreach/tables.md from measured files only: for each subject, the changes that make no noise (not
// additions, signal silent) and how current models did on them.
// - "No tools": docs/bench/2026-10-11-models/ (each model answered each change's A question twice, no tools).
// - "Claude Code in the project": docs/bench/2026-10-11-done3/ B answers without sync (read-only tools, web included,
//   new version installed).
//   node docs/outreach/make-tables.ts
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "../..");
const json = <T>(p: string): T => JSON.parse(readFileSync(join(root, p), "utf8")) as T;

interface Key {
  id: string;
  answer: string;
  signal?: string;
  symbol?: string;
}
const keys = json<{ changes: Key[] }>("docs/bench/2026-10-11-keys/keys.json").changes;

// Each change's kind, from its lesson on main (through replacements), when it has one.
const seedOf = json<Record<string, string>>("docs/bench/2026-10-11-done3/seeds.json");
const lessons = new Map<string, { kind: string; replaces?: string[] }>();
for (const s of readdirSync(join(root, "lessons"), { withFileTypes: true }).filter((d) => d.isDirectory())) {
  for (const f of readdirSync(join(root, "lessons", s.name)).filter((f) => f.endsWith(".json"))) {
    const l = json<{ id: string; kind?: string; replaces?: string[] }>(`lessons/${s.name}/${f}`);
    if (l.kind) lessons.set(l.id, { kind: l.kind, replaces: l.replaces });
  }
}
const kindOf = (change: string): string | undefined => {
  const id = seedOf[change];
  if (!id) return undefined;
  const replacing = [...lessons.entries()].find(([, l]) => l.replaces?.includes(id));
  return (replacing?.[1] ?? lessons.get(id))?.kind;
};

// No tools: right answers per model, out of two.
const modelsDir = "docs/bench/2026-10-11-models";
const aQuestions = json<{ id: string; change: string }[]>(`${modelsDir}/questions.json`);
const noTools: Record<string, Record<string, number>> = {};
for (const f of readdirSync(join(root, modelsDir)).filter((f) => f.startsWith("grades-A-none-"))) {
  const model = f.replace("grades-A-none-", "").replace(/-\d\.json$/, "");
  for (const g of json<{ grades: { id: string; grade: string }[] }>(`${modelsDir}/${f}`).grades) {
    const change = aQuestions.find((q) => q.id === g.id)!.change;
    (noTools[change] ??= {})[model] = (noTools[change]![model] ?? 0) + (g.grade === "correct" ? 1 : 0);
  }
}

// Claude Code in the project, without sync (B questions).
const bQuestions = json<{ id: string; change: string }[]>("docs/bench/2026-10-11-done3/questions.json");
const inProject = new Map(json<{ grades: { id: string; grade: string }[] }>("docs/bench/2026-10-11-done3/grades-B-project.json").grades.map((g) => [bQuestions.find((q) => q.id === g.id)!.change, g.grade]));

const MODELS = ["claude-haiku-5-5", "claude-sonnet-5-5", "claude-opus-5-5"];
const subjects = [...new Set(keys.map((k) => k.id.split("-")[0]!))];
const lines = [
  "# Changes current models get wrong without a sound",
  "",
  "Generated by `docs/outreach/make-tables.ts` from measured files only. A row is a change that isn't an addition and that code written for the older version survives without an error (\"silent\" in the verified answer keys, `docs/bench/2026-10-11-keys/`).",
  "",
  "- **No tools**: right answers out of 2 per model (Claude Haiku, Sonnet, Opus 5.5), each answering the change's question with no tools (`docs/bench/2026-10-11-models/`, 2026-10-11).",
  "- **Claude Code in the project**: Claude Code (`claude-opus-5-5`) with its read-only tools (read, search, web search and fetch, and a few fixed commands such as `npm ls`), in a project with the new version installed, without Ludion: the grade of its one answer (`docs/bench/2026-10-11-done3/`, B questions, 2026-10-11).",
  "",
];
for (const subject of subjects) {
  const rows = keys.filter((k) => k.id.startsWith(`${subject}-`) && k.signal === "silent" && kindOf(k.id) !== "added");
  if (!rows.length) continue;
  lines.push(`## ${subject}`, "", "| change | what is true now | no tools (Haiku / Sonnet / Opus) | Claude Code in the project |", "| - | - | - | - |");
  for (const k of rows) {
    const nt = MODELS.map((m) => `${noTools[k.id]?.[m] ?? "-"}/2`).join(" / ");
    lines.push(`| ${k.id} | ${k.answer.replace(/\|/g, "\\|").replace(/\n/g, " ")} | ${nt} | ${inProject.get(k.id) ?? "-"} |`);
  }
  const wrongInProject = rows.filter((k) => inProject.get(k.id) !== "correct").length;
  lines.push("", `${rows.length} such changes; Claude Code in the project answered ${wrongInProject} of them wrong or not at all.`, "");
}
writeFileSync(join(import.meta.dirname, "tables.md"), lines.join("\n"));
console.log("Wrote docs/outreach/tables.md");
