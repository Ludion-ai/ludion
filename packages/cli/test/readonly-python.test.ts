describe("Pipfile.lock", () => {
  it("reads exact ==versions in every category and lists git and path entries", () => {
    const result = parsePipfileLock(PIPFILE_LOCK, new Set(["jinja2", "iniconfig"]));
    expect(ids(result.packages)).toEqual(["iniconfig@2.0.0*", "jinja2@2.11.2*", "markupsafe@3.0.4"]);
    expect(result.project).toEqual(["demo"]);
    expect(result.limitations).toEqual(["Pipfile.lock: 2 packages come from git, URL or local path sources rather than a registry and were not checked against advisories: locallib (path), six (git)."]);
  });

  it("lists inexact versions, and does not guess at another pipfile-spec", () => {
    const lock = JSON.parse(PIPFILE_LOCK);
    lock.default.markupsafe.version = "===3.0.4";
    lock.develop.iniconfig.version = "*";
    lock.docs = { sphinx: { version: "==7.0.0" } };
    const result = parsePipfileLock(JSON.stringify(lock));
    expect(ids(result.packages)).toEqual(["jinja2@2.11.2", "sphinx@7.0.0"]);
    expect(result.limitations[1]).toBe('Pipfile.lock: 2 packages have no exact ==version, so they were not checked: markupsafe ("===3.0.4"), iniconfig ("*").');
    lock._meta["pipfile-spec"] = 7;
    expect(parsePipfileLock(JSON.stringify(lock))).toEqual({ packages: [], project: [], limitations: ["Pipfile.lock has pipfile-spec 7; this reader knows spec 6 only, so its packages were not read."] });
  });

  it("refuses a lock it cannot read", () => {
    expect(() => parsePipfileLock("{")).toThrow(/Pipfile\.lock is not valid JSON/);
    expect(() => parsePipfileLock("[]")).toThrow(/not a JSON object/);
    expect(() => parsePipfileLock(JSON.stringify({ _meta: { "pipfile-spec": 6 }, default: [] }))).toThrow(/"default" is not a map of packages/);
    expect(() => parsePipfileLock(JSON.stringify({ _meta: { "pipfile-spec": 6 }, default: { "bad name": { version: "==1.0" } } }))).toThrow(/not a valid package entry/);
  });
});

