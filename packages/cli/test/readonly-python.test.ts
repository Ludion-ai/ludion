describe("Python TOML reader", () => {
  it("reads the lock file subset with TOML's table rules", () => {
    const doc = parseToml(`# comment
version = 1
[[package]]
name = "a" # trailing comment
source = { registry = "https://pypi.org/simple" }
deps = [
  { name = "b", extra = ["x", 'y'] },  # inline tables across lines
  { name = "c" },
]
[package.metadata]
note = "tab\\tquote\\" \\u00e9"
literal = 'C:\\path'
text = """
two
lines"""
size = 1_024
ratio = 0.5
flag = true
[package.metadata.deep]
dotted.key = "v"
[[package]]
name = "d"
`, "t.toml");
    expect(doc.version).toBe(1);
    const [a, d] = doc.package as any[];
    expect(a.name).toBe("a");
    expect(a.source).toEqual({ registry: "https://pypi.org/simple" });
    expect(a.deps).toEqual([{ name: "b", extra: ["x", "y"] }, { name: "c" }]);
    expect(a.metadata).toMatchObject({ note: "tab\tquote\" é", literal: "C:\\path", text: "two\nlines", size: 1024, ratio: 0.5, flag: true });
    expect(a.metadata.deep.dotted.key).toBe("v");
    expect(d.name).toBe("d");
    expect(parseToml('\uFEFFversion = 1\r\n[[package]]\r\nname = "a"\r\n', "t.toml")).toEqual({ version: 1, package: [{ name: "a" }] });
    expect(() => parseToml('version = 1\r[[package]]\n', "t.toml")).toThrow(/line 1/);
  });

  it.each([
    ["a duplicate key", '[[package]]\nname = "a"\nname = "b"\n', /line 3: duplicate key "name"/],
    ["a sub-table defined twice in one package", '[[package]]\nname = "a"\n[package.source]\ntype = "git"\n[package.source]\ntype = "legacy"\n', /line 5: table "package\.source" is defined more than once/],
    ["an array of tables over a table", '[package]\nname = "a"\n[[package]]\n', /line 3: .*not an array of tables/],
    ["a header extending an inline table", 'source = { registry = "x" }\n[source.extra]\n', /line 2: .*not a table/],
    ["a dotted key extending an inline table", 'a = { b = 1 }\na.c = 2\n', /line 2: .*already defined/],
    ["an unterminated string", '[[package]]\nname = "a\n', /line 2: unterminated string/],
    ["a version written without quotes", '[[package]]\nname = "a"\nversion = 2.19.0\n', /line 3: unsupported value "2.19.0"/],
    ["a date", 'when = 2026-10-28\n', /line 1: unsupported value/],
    ["two values on one line", 'a = "b" c = "d"\n', /line 1: expected the end of the line/],
    ["an unknown escape", 'a = "\\q"\n', /line 1: unknown escape/],
    ["an unclosed array", 'a = ["b",\n', /expected a value/],
    ["a missing comma in an inline table", 'a = { b = "c" d = "e" }\n', /expected , or \}/],
    ["values nested too deeply", `a = ${"[".repeat(40)}${"]".repeat(40)}\n`, /nest more than 32 levels/],
    ["a key without a value", '[[package]]\nname\n', /line 2: expected = after a key/],
  ])("refuses %s, naming the file and line", (_label, text, error) => {
    expect(() => parseToml(text, "uv.lock")).toThrow(error);
    expect(() => parseToml(text, "uv.lock")).toThrow(/^uv\.lock line \d+: .*the file was not read\.$/);
  });
});

