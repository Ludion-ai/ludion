function project(files: Record<string, string>): string {
  const root = mkdtempSync(join(tmpdir(), "ludion-readonly-registered-"));
  for (const [name, text] of Object.entries(files)) writeFileSync(join(root, name), text);
  return root;
}
const readOnly = (check: Awaited<ReturnType<typeof scanProject>>["checks"][number]) => {
  if (!("result" in check) || !("fixed_versions_note" in check.result)) throw new Error(`not a read-only result: ${JSON.stringify(check)}`);
  return check.result;
};

describe("the registered readers", () => {
  it("are Python, Go and Rust, in that order", () => {
    expect(READONLY_READERS.map(r => [r.ecosystem, r.files])).toEqual([
      ["PyPI", ["requirements.txt", "pyproject.toml", "poetry.lock", "uv.lock", "Pipfile.lock", "Pipfile"]],
      ["Go", ["go.mod"]],
      ["crates.io", ["Cargo.lock", "Cargo.toml"]],
    ]);
  });
});

describe("scanProject with the registered readers", () => {
  it("Python: reads uv.lock, sends the locked names and versions, and lists OSV's fixed versions", async () => {
    const seen: Query[] = [];
    const report = await scanProject(project(PYTHON), undefined, { client: new OsvClient(osv({ "PyPI:requests@2.19.0": ["GHSA-x84v-xcm2-53pg"] }, seen)) });
    expect(report.checks.map(c => c.ecosystem)).toEqual(["PyPI"]);
    const result = readOnly(report.checks[0]!);
    // uv.lock records pyproject.toml's requirements, so pyproject.toml is covered, not "present but not read".
    expect(result.inventory.files).toEqual(["uv.lock"]);
    expect(result.inventory.limitations).toEqual([]);
    expect(result.inventory.packages).toEqual([{ name: "requests", version: "2.19.0", direct: true }, { name: "urllib3", version: "1.23", direct: false }]);
    expect(seen).toEqual([{ package: { ecosystem: "PyPI", name: "requests" }, version: "2.19.0" }, { package: { ecosystem: "PyPI", name: "urllib3" }, version: "1.23" }]);
    expect(result.findings.map(f => [f.package.name, f.advisory.id, f.kind, f.fixed_versions])).toEqual([["requests", "GHSA-x84v-xcm2-53pg", "vulnerability", ["2.20.0"]]]);
    expect(result.status).toBe("vulnerabilities_found");
    expect(report.unsupported).toEqual([]);
  });
  it("Go: a toolchain line adds stdlib and toolchain with a limitation, so no findings is incomplete", async () => {
    const seen: Query[] = [];
    const report = await scanProject(project({ "go.mod": GO_MOD }), undefined, { client: new OsvClient(osv({}, seen)) });
    const result = readOnly(report.checks[0]!);
    expect(report.checks.map(c => c.ecosystem)).toEqual(["Go"]);
    expect(seen.map(q => `${q.package.name}@${q.version}`)).toEqual(["golang.org/x/net@v0.7.0", "golang.org/x/text@v0.3.7", "stdlib@1.22.5", "toolchain@1.22.5"]);
    expect(result.inventory.limitations).toHaveLength(1);
    expect(result.inventory.limitations[0]).toMatch(/^stdlib and toolchain were checked at 1\.22\.5, go\.mod's toolchain line, but that line is only a minimum/);
    expect(result.status).toBe("incomplete");
    expect(report.status).toBe("attention_required");
    expect(report.unsupported).toEqual([]);
  });
  it("Rust: reads Cargo.lock, covers Cargo.toml, and keeps informational and unsound RustSec records apart", async () => {
    const root = project(RUST);
    const informational = await scanProject(root, undefined, { client: new OsvClient(osv({ "crates.io:atty@0.2.14": ["RUSTSEC-2024-0375"] })) });
    const result = readOnly(informational.checks[0]!);
    expect(result.inventory.files).toEqual(["Cargo.lock"]);
    expect(result.inventory.limitations).toEqual([]);
    expect(result.inventory.packages).toEqual([{ name: "atty", version: "0.2.14", direct: true }, { name: "libc", version: "0.2.150", direct: false }]);
    expect(result.findings.map(f => [f.advisory.id, f.kind])).toEqual([["RUSTSEC-2024-0375", "informational"]]);
    expect(result.status).toBe("no_known_vulnerabilities");
    expect(informational.status).toBe("no_known_updates");
    const unsound = await scanProject(root, undefined, { client: new OsvClient(osv({ "crates.io:atty@0.2.14": ["RUSTSEC-2024-0375", "RUSTSEC-2021-0145"] })) });
    expect(readOnly(unsound.checks[0]!).findings.map(f => [f.advisory.id, f.kind])).toEqual([["RUSTSEC-2024-0375", "informational"], ["RUSTSEC-2021-0145", "vulnerability"]]);
    expect(unsound.status).toBe("attention_required");
  });
  it("a mixed project: npm unchanged, one check per read-only ecosystem, and only Gradle left unsupported", async () => {
    const vulns = { "npm:lodash@4.17.20": ["GHSA-35jh-r3h4-6jhm"], "PyPI:requests@2.19.0": ["GHSA-x84v-xcm2-53pg"], "crates.io:atty@0.2.14": ["RUSTSEC-2024-0375"] };
    const files = { ...NPM, ...PYTHON, "go.mod": GO_MOD, ...RUST, "requirements.txt": "urllib3==1.23\n", "build.gradle": "", "build.gradle.kts": "" };
    const mixed = await scanProject(project(files), undefined, { client: new OsvClient(osv(vulns)) });
    expect(mixed.checks.map(c => c.ecosystem)).toEqual(["npm", "PyPI", "Go", "crates.io"]);
    expect(mixed.unsupported).toEqual(["build.gradle", "build.gradle.kts"]);
    // npm's check is the one an npm-only project gets.
    const npmOnly = await scanProject(project(NPM), undefined, { client: new OsvClient(osv(vulns)) });
    const strip = (value: unknown) => JSON.parse(JSON.stringify(value, (key, v) => key === "checked_at" ? undefined : v));
    expect(strip(mixed.checks[0])).toEqual(strip(npmOnly.checks[0]));
    expect("result" in mixed.checks[0]! && "plan" in mixed.checks[0].result && mixed.checks[0].result.plan).toEqual([{ name: "lodash", from: "4.17.20", to: "4.17.21", advisories: ["GHSA-35jh-r3h4-6jhm"] }]);
    // The Python reader read uv.lock and requirements.txt; pyproject.toml is covered by uv.lock.
    expect(readOnly(mixed.checks[1]!).inventory.files).toEqual(["uv.lock", "requirements.txt"]);
    // Before registration the same folder listed the Python, Go and Rust files as unsupported.
    const before = await scanProject(project(files), undefined, { readers: [], client: new OsvClient(osv(vulns)) });
    expect(before.checks.map(c => c.ecosystem)).toEqual(["npm"]);
    expect(before.unsupported).toEqual(["requirements.txt", "pyproject.toml", "go.mod", "Cargo.lock", "build.gradle", "build.gradle.kts"]);
  });
});

describe("ludion scan with the registered readers", () => {
  let out: string[], err: string[];
  beforeEach(() => {
    out = []; err = [];
    vi.spyOn(console, "log").mockImplementation((line: string) => { out.push(line); });
    vi.spyOn(console, "error").mockImplementation((line: string) => { err.push(line); });
  });
  afterEach(() => { vi.restoreAllMocks(); vi.unstubAllGlobals(); });
  const scan = (files: Record<string, string>, vulns: Record<string, string[]>, ...args: string[]) => {
    vi.stubGlobal("fetch", osv(vulns));
    return securityCli("scan", ["--dir", project(files), ...args]);
  };

  it("Python: exit 1 on a match, exit 0 when OSV knows nothing", async () => {
    expect(await scan(PYTHON, { "PyPI:requests@2.19.0": ["GHSA-x84v-xcm2-53pg"] })).toBe(1);
    expect(out).toContain("PyPI: 2 package versions · 1 advisory matches · vulnerabilities_found");
    expect(out).toContain("  requests@2.19.0 · GHSA-x84v-xcm2-53pg · Insufficiently Protected Credentials in Requests · OSV lists fixed: 2.20.0");
    expect(out).toContain("  Read-only: Ludion reports known advisories for this ecosystem but does not plan or apply updates.");
    expect(await scan(PYTHON, {})).toBe(0);
  });
  it("Go: exit 2 when nothing matches (the toolchain limitation), exit 1 on a stdlib match", async () => {
    expect(await scan({ "go.mod": GO_MOD }, {}, "--ecosystem", "go")).toBe(2);
    expect(out.some(line => line.startsWith("  Incomplete: stdlib and toolchain were checked at 1.22.5"))).toBe(true);
    expect(await scan({ "go.mod": GO_MOD }, { "Go:stdlib@1.22.5": ["GO-2026-0001"] })).toBe(1);
    expect(out).toContain("  stdlib@1.22.5 · GO-2026-0001 · Example net/http issue · OSV lists fixed: 1.22.7");
  });
  it("Rust: exit 0 on an informational-only match, exit 1 on an unsound one", async () => {
    expect(await scan(RUST, { "crates.io:atty@0.2.14": ["RUSTSEC-2024-0375"] })).toBe(0);
    expect(out).toContain("  Informational (unmaintained, not counted as a vulnerability): atty@0.2.14 · RUSTSEC-2024-0375 · `atty` is unmaintained · OSV lists no fixed version");
    expect(await scan(RUST, { "crates.io:atty@0.2.14": ["RUSTSEC-2021-0145"] })).toBe(1);
    expect(out).toContain("  atty@0.2.14 · RUSTSEC-2021-0145 · Potential unaligned read · OSV lists no fixed version");
  });
  it("a mixed project prints npm as before, then each read-only check, and names only Gradle as unsupported", async () => {
    const files = { ...NPM, ...PYTHON, "go.mod": GO_MOD, ...RUST, "build.gradle": "" };
    expect(await scan(files, { "npm:lodash@4.17.20": ["GHSA-35jh-r3h4-6jhm"] })).toBe(1);
    expect(out.filter(line => !line.startsWith("  "))).toEqual([
      "npm: 1 package versions · 1 advisory matches · vulnerabilities_found",
      "PyPI: 2 package versions · 0 advisory matches · no_known_vulnerabilities",
      "Go: 4 package versions · 0 advisory matches · incomplete",
      "crates.io: 2 package versions · 0 advisory matches · no_known_vulnerabilities",
      "Known data only; no match is not a security guarantee. Dependency coordinates are sent to OSV; source stays local to your Docker setup.",
    ]);
    expect(out.slice(0, 4)).toEqual(["npm: 1 package versions · 1 advisory matches · vulnerabilities_found", "  lodash@4.17.20 · GHSA-35jh-r3h4-6jhm · Command Injection in lodash", "  Scope: locked_dependencies", "PyPI: 2 package versions · 0 advisory matches · no_known_vulnerabilities"]);
    expect(err).toEqual(["Unsupported inventories: build.gradle. These have not been checked."]);
  });
  it("--ecosystem python scans only Python in a mixed project", async () => {
    vi.stubGlobal("fetch", osv({}));
    const root = project({ ...NPM, ...PYTHON, "go.mod": GO_MOD });
    expect(await securityCli("scan", ["--dir", root, "--ecosystem", "python", "--json"])).toBe(0);
    const report = JSON.parse(out.join("\n"));
    expect(report.checks.map((c: { ecosystem: string }) => c.ecosystem)).toEqual(["PyPI"]);
    expect(report.unsupported).toEqual([]);
  });
});
