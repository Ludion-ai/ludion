type Query = { package: { ecosystem: string; name: string }; version: string };
/** OSV: advisory ids by "ecosystem:name@version", and the records by id. Every batch query is kept. */
function osv(vulns: Record<string, string[]>, seen: Query[] = []): typeof fetch {
  return async (url, init) => {
    const id = decodeURIComponent(String(url).split("/vulns/")[1] ?? "");
    if (id) return RECORDS[id] ? response(RECORDS[id]) : new Response("", { status: 404 });
    const queries: Query[] = JSON.parse(String(init?.body)).queries;
    seen.push(...queries);
    return response({ results: queries.map(q => { const ids = vulns[`${q.package.ecosystem}:${q.package.name}@${q.version}`] ?? []; return ids.length ? { vulns: ids.map(id => ({ id })) } : {}; }) });
  };
}
