import { mkdirSync, mkdtempSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { parseCargoLock, readRust, RUST_SCOPE } from "../src/security/readonly/rust.ts";

const CRATES = "registry+https://github.com/rust-lang/crates.io-index";
const SPARSE = "sparse+https://index.crates.io/";
const HEAD = "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\n";
const sum = (c: string) => c.repeat(64);
/** One [[package]] table as Cargo writes it. */
function pkg(name: string, version: string, extra: { source?: string; checksum?: string; dependencies?: string[]; replace?: string } = {}): string {
  let out = `[[package]]\nname = "${name}"\nversion = "${version}"\n`;
  if (extra.source) out += `source = "${extra.source}"\n`;
  if (extra.checksum) out += `checksum = "${extra.checksum}"\n`;
  if (extra.dependencies) out += `dependencies = [\n${extra.dependencies.map(d => ` "${d}",\n`).join("")}]\n`;
  if (extra.replace) out += `replace = "${extra.replace}"\n`;
  return `${out}\n`;
}
function project(files: Record<string, string>): string {
  const root = mkdtempSync(join(tmpdir(), "ludion-rust-test-"));
  for (const [name, text] of Object.entries(files)) writeFileSync(join(root, name), text);
  return root;
}

const V1 = `[[package]]
name = "app"
version = "0.1.0"
dependencies = [
 "serde 1.0.100 (${CRATES})",
 "time 0.1.43 (${CRATES})",
]

[[package]]
name = "libc"
version = "0.2.80"
source = "${CRATES}"

[[package]]
name = "serde"
version = "1.0.100"
source = "${CRATES}"

[[package]]
name = "time"
version = "0.1.43"
source = "${CRATES}"
dependencies = [
 "libc 0.2.80 (${CRATES})",
]

[metadata]
"checksum libc 0.2.80 (${CRATES})" = "${sum("a")}"
"checksum serde 1.0.100 (${CRATES})" = "${sum("b")}"
"checksum time 0.1.43 (${CRATES})" = "<none>"
`;
const V3 = `${HEAD}version = 3

${pkg("app", "0.1.0", { dependencies: ["smallvec", "time"] })}${pkg("libc", "0.2.80", { source: CRATES, checksum: sum("a") })}${pkg("smallvec", "1.6.0", { source: CRATES, checksum: sum("b") })}${pkg("time", "0.1.43", { source: CRATES, checksum: sum("c"), dependencies: ["libc"] })}`;

describe("Cargo.lock formats", () => {
  it("reads v1 with its [metadata] checksum table and full package ids", () => {
    expect(parseCargoLock(V1)).toEqual({
      packages: [{ name: "libc", version: "0.2.80", direct: false }, { name: "serde", version: "1.0.100", direct: true }, { name: "time", version: "0.1.43", direct: true }],
      limitations: [],
    });
  });
  it("reads the oldest v1 layout, where the root package is a [root] table", () => {
    const text = `[root]\nname = "app"\nversion = "0.1.0"\ndependencies = [\n "smallvec 0.6.5 (${CRATES})",\n]\n\n${pkg("smallvec", "0.6.5", { source: CRATES })}${pkg("unrelated", "1.0.0", { source: CRATES })}`;
    expect(parseCargoLock(text).packages).toEqual([{ name: "smallvec", version: "0.6.5", direct: true }, { name: "unrelated", version: "1.0.0", direct: false }]);
    expect(() => parseCargoLock(text.replace('[root]\nname = "app"', `[root]\nname = "app"\nsource = "${CRATES}"`))).toThrow("[root] package has no source");
  });
  it("reads v2 (no version marker, inline checksums, minimal ids)", () => {
    const text = `${HEAD}${pkg("app", "0.1.0", { dependencies: ["smallvec"] })}${pkg("smallvec", "1.6.0", { source: CRATES, checksum: sum("b") })}`;
    expect(parseCargoLock(text)).toEqual({ packages: [{ name: "smallvec", version: "1.6.0", direct: true }], limitations: [] });
  });
  it("reads v3 and v4, with crates.io as the git index id or the sparse URL", () => {
    const expected = [{ name: "libc", version: "0.2.80", direct: false }, { name: "smallvec", version: "1.6.0", direct: true }, { name: "time", version: "0.1.43", direct: true }];
    expect(parseCargoLock(V3)).toEqual({ packages: expected, limitations: [] });
    expect(parseCargoLock(V3.replace("version = 3", "version = 4").replaceAll(CRATES, SPARSE))).toEqual({ packages: expected, limitations: [] });
  });
  it("counts one package for the same crate version from both crates.io ids, direct if either is", () => {
    const text = `version = 4\n\n${pkg("app", "0.1.0", { dependencies: [`serde 1.0.1 (${SPARSE})`] })}${pkg("serde", "1.0.1", { source: CRATES, checksum: sum("a") })}${pkg("serde", "1.0.1", { source: SPARSE, checksum: sum("a") })}`;
    expect(parseCargoLock(text).packages).toEqual([{ name: "serde", version: "1.0.1", direct: true }]);
  });
  it("reports an unknown format version instead of guessing, whatever follows it", () => {
    for (const version of ["5", "2", "1", "0", "03"]) {
      expect(parseCargoLock(V3.replace("version = 3", `version = ${version}`))).toEqual({ packages: [], limitations: [`Cargo.lock format version ${version} is not one Ludion reads (1 to 4); its packages were not read or checked.`] });
    }
    expect(parseCargoLock(`version = 5\nfuture = { inline = "table" }\n\n[[future.table]]\nname = 1\n`).limitations[0]).toContain("version 5 is not one Ludion reads");
    expect(parseCargoLock("version = 7\n").packages).toEqual([]);
  });
  it("reads multi-line dependency arrays with comments, blank lines, CRLF, tabs and escapes", () => {
    const text = `version = 3 # format\r\n\r\n[[package]]\r\nname = "app"\r\nversion = "0.1.0"\r\ndependencies = [ # what app uses\r\n\t"smallvec",\r\n\r\n  # time is pinned\r\n  "time" ]\r\n\r\n[[package]]\r\nname = "\\u0073mallvec"\r\nversion = "1.6.0"\r\nsource = "${CRATES}"\r\n[[package]]\r\nname = "time"\r\nversion = "0.1.43"\r\nsource = "${CRATES}"\r\ndependencies = []\r\n`;
    expect(parseCargoLock(text)).toEqual({ packages: [{ name: "smallvec", version: "1.6.0", direct: true }, { name: "time", version: "0.1.43", direct: true }], limitations: [] });
  });
  it("reads real-world version strings: pre-releases and build metadata", () => {
    const text = `version = 4\n\n${pkg("app", "0.1.0", { dependencies: ["openssl-src", "tokio"] })}${pkg("openssl-src", "300.3.2+3.3.2", { source: CRATES })}${pkg("tokio", "2.0.0-alpha.1", { source: CRATES })}`;
    expect(parseCargoLock(text).packages.map(p => p.version)).toEqual(["300.3.2+3.3.2", "2.0.0-alpha.1"]);
  });
});

describe("Cargo.lock sources, members and direct dependencies", () => {
  const WORKSPACE = `version = 4

${pkg("app", "0.1.0", { dependencies: ["core", "serde"] })}${pkg("core", "0.2.0", { dependencies: ["smallvec 1.6.0"] })}${pkg("serde", "1.0.200", { source: SPARSE, checksum: sum("a"), dependencies: ["smallvec 0.6.14"] })}${pkg("smallvec", "0.6.14", { source: SPARSE, checksum: sum("b") })}${pkg("smallvec", "1.6.0", { source: SPARSE, checksum: sum("c") })}`;
  it("skips workspace members and path crates, and makes what they name direct", () => {
    // app and core have no source: they are the project. core is a path crate, so smallvec 1.6.0 is direct.
    expect(parseCargoLock(WORKSPACE)).toEqual({
      packages: [{ name: "serde", version: "1.0.200", direct: true }, { name: "smallvec", version: "0.6.14", direct: false }, { name: "smallvec", version: "1.6.0", direct: true }],
      limitations: [],
    });
  });
  it("resolves `name version` exactly when a name has several versions, and refuses an ambiguous or missing id", () => {
    expect(() => parseCargoLock(WORKSPACE.replace('"smallvec 1.6.0"', '"smallvec"'))).toThrow('Invalid Cargo.lock: core 0.2.0 depends on "smallvec", which matches more than one [[package]].');
    expect(() => parseCargoLock(WORKSPACE.replace('"smallvec 1.6.0"', '"smallvec 1.6.9"'))).toThrow('depends on "smallvec 1.6.9", which matches no [[package]]');
    expect(() => parseCargoLock(WORKSPACE.replace('"serde",', '"tokio",'))).toThrow("matches no [[package]]");
  });
  it("names git crates in a limitation and resolves the same version from git and crates.io by source", () => {
    const git = "git+https://github.com/example/hyper?branch=fix";
    const text = `version = 3

${pkg("app", "0.1.0", { dependencies: [`hyper 0.14.0 (${git})`, "reqwest"] })}${pkg("hyper", "0.14.0", { source: `${git}#0123456789abcdef0123456789abcdef01234567` })}${pkg("hyper", "0.14.0", { source: CRATES, checksum: sum("d") })}${pkg("reqwest", "0.11.0", { source: CRATES, checksum: sum("e"), dependencies: [`hyper 0.14.0 (${CRATES})`] })}`;
    expect(parseCargoLock(text)).toEqual({
      packages: [{ name: "hyper", version: "0.14.0", direct: false }, { name: "reqwest", version: "0.11.0", direct: true }],
      limitations: ["Crates from git sources are outside crates.io advisory coverage and were not checked (1): hyper 0.14.0."],
    });
    expect(parseCargoLock(text.replace(`hyper 0.14.0 (${git})`, `hyper 0.14.0 (${CRATES})`)).packages[0]).toEqual({ name: "hyper", version: "0.14.0", direct: true });
    expect(() => parseCargoLock(text.replace(`hyper 0.14.0 (${git})`, "hyper 0.14.0"))).toThrow("matches more than one [[package]]");
  });
  it("bounds the list of crates it names", () => {
    const names = Array.from({ length: 12 }, (_, n) => `forked${n}`);
    const text = `version = 4\n\n${pkg("app", "0.1.0", { dependencies: names })}${names.map(n => pkg(n, "1.0.0", { source: `git+https://example.com/${n}#${"f".repeat(40)}` })).join("")}`;
    const { packages, limitations } = parseCargoLock(text);
    expect(packages).toEqual([]);
    expect(limitations).toEqual([`Crates from git sources are outside crates.io advisory coverage and were not checked (12): ${names.slice(0, 10).map(n => `${n} 1.0.0`).join(", ")} and 2 more.`]);
  });
  it("names crates from other registries or a recorded path, and never sends them as crates.io", () => {
    const text = `version = 4\n\n${pkg("app", "0.1.0", { dependencies: ["internal", "mirrored", "vendored"] })}${pkg("internal", "2.0.0", { source: "registry+https://registry.example.com/index", checksum: sum("1") })}${pkg("mirrored", "1.0.0", { source: "sparse+https://index.crates.io.example.com/", checksum: sum("2") })}${pkg("vendored", "0.3.0", { source: "path+file:///src/vendored" })}`;
    expect(parseCargoLock(text)).toEqual({ packages: [], limitations: ["Crates from registries other than crates.io, or from a recorded path, were not checked (3): internal 2.0.0, mirrored 1.0.0, vendored 0.3.0."] });
  });
  it("does not read a crate replaced through [replace] as the one that is built", () => {
    const git = "git+https://example.com/foo";
    const text = `${pkg("app", "0.1.0", { dependencies: [`foo 0.1.0 (${CRATES})`] })}${pkg("foo", "0.1.0", { source: CRATES, replace: `foo 0.1.0 (${git})` })}${pkg("foo", "0.1.0", { source: `${git}#${"a".repeat(40)}` })}`;
    expect(parseCargoLock(text)).toEqual({ packages: [], limitations: [
      "Crates from git sources are outside crates.io advisory coverage and were not checked (1): foo 0.1.0.",
      "Crates replaced through [replace] are not built and were not checked; each replacement is read by its own source (1): foo 0.1.0.",
    ] });
  });
  it("validates [[patch.unused]] but does not count patches Cargo did not use", () => {
    const text = `${V3}[[patch.unused]]\nname = "bar"\nversion = "0.2.0"\nsource = "git+https://example.com/bar#${"b".repeat(40)}"\n`;
    expect(parseCargoLock(text)).toEqual(parseCargoLock(V3));
    expect(() => parseCargoLock(`${V3}[[patch.unused]]\nname = "bar"\n`)).toThrow('[[patch.unused]] #1 "bar" at line 34: missing version');
  });
  it("says when no workspace member is listed, since direct dependencies are then unknown, including for an empty file", () => {
    const limitation = "Cargo.lock lists no workspace member (a package without a source), so direct dependencies could not be identified.";
    expect(parseCargoLock(`version = 3\n\n${pkg("serde", "1.0.1", { source: CRATES })}`)).toEqual({ packages: [{ name: "serde", version: "1.0.1", direct: false }], limitations: [limitation] });
    expect(parseCargoLock("")).toEqual({ packages: [], limitations: [limitation] });
    expect(parseCargoLock(HEAD)).toEqual({ packages: [], limitations: [limitation] });
  });
  it("throws above 2,000 distinct crates.io package versions", () => {
    const many = (n: number) => `version = 4\n\n${pkg("app", "0.1.0")}${Array.from({ length: n }, (_, i) => pkg("crate", `1.0.${i}`, { source: CRATES })).join("")}`;
    expect(parseCargoLock(many(2000)).packages).toHaveLength(2000);
    expect(() => parseCargoLock(many(2001))).toThrow("exceeds 2,000 distinct crates.io package versions");
  });
});

describe("malformed Cargo.lock never becomes a partial result", () => {
  const one = (body: string) => `version = 3\n\n[[package]]\n${body}`;
  it.each([
    ["a package without a version", one(`name = "serde"\nsource = "${CRATES}"\n`), '[[package]] #1 "serde" at line 3: missing version'],
    ["a package without a name", one(`version = "1.0.0"\n`), "[[package]] #1 at line 3: missing name"],
    ["a range instead of a version", one(`name = "serde"\nversion = "1.0"\n`), 'version "1.0" is not an exact semver version'],
    ["a leading-zero version", one(`name = "serde"\nversion = "01.0.0"\n`), "not an exact semver version"],
    ["a version that is not a string", one(`name = "serde"\nversion = 1\n`), "version must be a string"],
    ["an unknown package key", one(`name = "serde"\nversion = "1.0.0"\nfeatures = []\n`), 'unsupported key "features"'],
    ["dependencies that are not an array", one(`name = "serde"\nversion = "1.0.0"\ndependencies = "libc"\n`), "dependencies must be an array of strings"],
    ["an invalid crate name", one(`name = "ser de"\nversion = "1.0.0"\n`), 'invalid crate name "ser de"'],
    ["a non-ASCII crates.io name", one(`name = "sérde"\nversion = "1.0.0"\nsource = "${CRATES}"\n`), "not a valid crates.io crate name"],
    ["an unsupported source protocol", one(`name = "serde"\nversion = "1.0.0"\nsource = "unknown+https://example.com"\n`), 'unsupported source "unknown+https://example.com"'],
    ["a source with no protocol", one(`name = "serde"\nversion = "1.0.0"\nsource = "https://example.com"\n`), "unsupported source"],
    ["a checksum that is not SHA-256", one(`name = "serde"\nversion = "1.0.0"\nchecksum = "abc"\n`), "checksum is not a SHA-256 hex digest"],
    ["a package id with an unbracketed source", one(`name = "app"\nversion = "1.0.0"\ndependencies = ["serde 1.0.0 ${CRATES}"]\n`), "invalid package id"],
    ["a package id with a range", one(`name = "app"\nversion = "1.0.0"\ndependencies = ["serde ^1.0"]\n`), 'invalid package id "serde ^1.0"'],
    ["an empty package id", one(`name = "app"\nversion = "1.0.0"\ndependencies = [""]\n`), 'invalid package id ""'],
    ["a package listed twice", `version = 3\n\n${pkg("serde", "1.0.0", { source: CRATES })}${pkg("serde", "1.0.0", { source: CRATES })}`, "serde 1.0.0 (\"registry+https://github.com/rust-lang/crates.io-index\") is listed twice"],
    ["an unterminated string", one(`name = "serde\nversion = "1.0.0"\n`), "line 4: unterminated string"],
    ["an unterminated array", one(`name = "app"\nversion = "1.0.0"\ndependencies = [\n "serde",\n`), "unterminated array"],
    ["an array of non-strings", one(`name = "app"\nversion = "1.0.0"\ndependencies = [1]\n`), "arrays may contain only strings"],
    ["a missing comma in an array", one(`name = "app"\nversion = "1.0.0"\ndependencies = ["a" "b"]\n`), "expected , or ] in array"],
    ["a duplicate key", one(`name = "serde"\nname = "serde"\nversion = "1.0.0"\n`), 'line 5: duplicate key "name"'],
    ["a duplicate key after a multi-line array", one(`name = "app"\nversion = "1.0.0"\ndependencies = [\n "a",\n]\ndependencies = []\n`), 'line 9: duplicate key "dependencies"'],
    ["an inline table", one(`name = "serde"\nversion = { workspace = true }\n`), "unsupported value"],
    ["a multi-line string", one(`name = """serde"""\nversion = "1.0.0"\n`), "multi-line strings are not supported"],
    ["a literal string", one(`name = 'serde'\nversion = "1.0.0"\n`), "unsupported value"],
    ["a dotted key", one(`name = "serde"\nversion = "1.0.0"\nsource.kind = "x"\n`), "dotted keys are not supported"],
    ["a control character", one(`name = "ser\u0001de"\nversion = "1.0.0"\n`), "control character in string"],
    ["a bad escape", one(`name = "ser\\qde"\nversion = "1.0.0"\n`), "invalid escape in string"],
    ["text after a value", one(`name = "serde" version = "1.0.0"\n`), "expected the end of the line"],
    ["an unsupported table", `${V3}[package]\nname = "x"\n`, 'unsupported table "[package]"'],
    ["an unknown array table", `${V3}[[packages]]\nname = "x"\n`, 'unsupported table "[[packages]]"'],
    ["a broken header", `${V3}[[package]\n`, "invalid table header"],
    ["[metadata] twice", `${V1}[metadata]\n`, "[metadata] appears twice"],
    ["a [metadata] value that is not a string", `${V1}"checksum x" = 1\n`, 'must be a string'],
    ["an unknown top-level key", `version = 3\nresolver = "2"\n`, 'unsupported top-level key "resolver"'],
    ["a format version that is not an integer", `version = "3"\n`, "the format version must be an integer"],
  ])("throws on %s", (_label, text, message) => {
    expect(() => parseCargoLock(text)).toThrow(message);
    expect(() => parseCargoLock(text)).toThrow("Invalid Cargo.lock");
  });
});

describe("readRust", () => {
  it("reads Cargo.lock from a project directory", () => {
    const root = project({ "Cargo.toml": '[package]\nname = "app"\nversion = "0.1.0"\n', "Cargo.lock": V3 });
    expect(readRust(root)).toEqual({ ecosystem: "crates.io", files: ["Cargo.lock"], scope: RUST_SCOPE, packages: parseCargoLock(V3).packages, limitations: [] });
  });
  it("reports a Cargo.toml without Cargo.lock as unlocked and unchecked, with no packages", () => {
    expect(readRust(project({ "Cargo.toml": '[package]\nname = "app"\nversion = "0.1.0"\n\n[dependencies]\nserde = "1"\n' }))).toEqual({
      ecosystem: "crates.io", files: ["Cargo.toml"], scope: RUST_SCOPE, packages: [],
      limitations: ["Cargo.toml has no Cargo.lock beside it, so its dependency versions are not locked and were not checked (a workspace member's Cargo.lock is at the workspace root)."],
    });
  });
  it("returns null when neither file exists", () => {
    expect(readRust(project({ "package.json": "{}" }))).toBeNull();
  });
  it("refuses symlinked, dangling, non-regular, oversized and malformed lock files instead of skipping them", () => {
    const linked = project({ "real.lock": V3 });
    symlinkSync(join(linked, "real.lock"), join(linked, "Cargo.lock"));
    expect(() => readRust(linked)).toThrow("Symlinks are not supported");
    const dangling = project({});
    symlinkSync(join(dangling, "missing.lock"), join(dangling, "Cargo.lock"));
    expect(() => readRust(dangling)).toThrow("Symlinks are not supported");
    const directory = project({});
    mkdirSync(join(directory, "Cargo.lock"));
    expect(() => readRust(directory)).toThrow("Expected a regular project file");
    expect(() => readRust(project({ "Cargo.lock": `${V3}#${" ".repeat(4 * 1024 * 1024)}\n` }))).toThrow("exceeds 4 MiB");
    expect(() => readRust(project({ "Cargo.lock": one() }))).toThrow("missing version");
    function one() { return `version = 3\n\n[[package]]\nname = "serde"\n`; }
  });
});
