const CRATES = "registry+https://github.com/rust-lang/crates.io-index";
const SPARSE = "sparse+https://index.crates.io/";
const HEAD = "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\n";
const sum = (c: string) => c.repeat(64);
/** One [[package]] table as Cargo writes it. */
function pkg(name: string, version: string, extra: { source?: string; checksum?: string; dependencies?: string[]; replace?: string } = {}): string {
  let out = `[[package]]\nname = "${name}"\nversion = "${version}"\n`;
  if (extra.source) out += `source = "${extra.source}"\n`;
  if (extra.checksum) out += `checksum = "${extra.checksum}"\n`;
  if (extra.dependencies) out += `dependencies = [\n${extra.dependencies.map(d => ` "${d}",\n`).join("")}]\n`;
  if (extra.replace) out += `replace = "${extra.replace}"\n`;
  return `${out}\n`;
}
function project(files: Record<string, string>): string {
  const root = mkdtempSync(join(tmpdir(), "ludion-rust-test-"));
  for (const [name, text] of Object.entries(files)) writeFileSync(join(root, name), text);
  return root;
}

